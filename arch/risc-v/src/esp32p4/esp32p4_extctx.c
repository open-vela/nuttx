/****************************************************************************
 * Public Functions
 ****************************************************************************/

/****************************************************************************
 * Name: riscv_initial_extctx_state
 ****************************************************************************/

void riscv_initial_extctx_state(struct tcb_s *tcb)
{
  memset(&tcb->xcp.regs[REG_INT_CTX_NDX + 1], 0,
         CONFIG_ARCH_RISCV_INTXCPT_EXTREGS * sizeof(uintreg_t));
}
